package l2tp

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync"

	"github.com/lucaswren/s2l/internal/model"
)

// xl2tpd 只认分号注释，不认 #（否则会报 occurs with no context）
const (
	confBegin = "; BEGIN s2l managed block - DO NOT EDIT"
	confEnd   = "; END s2l managed block"
)

// ConfManager 动态维护 /etc/xl2tpd/xl2tpd.conf
type ConfManager struct {
	path         string
	optionsPath  string
	chapPath     string
	mu           sync.Mutex
	changed      bool
	beforeChange func() error
}

func NewConfManager(path, optionsPath string, chapPath ...string) *ConfManager {
	if path == "" {
		path = "/etc/xl2tpd/xl2tpd.conf"
	}
	if optionsPath == "" {
		optionsPath = "/etc/ppp/options.xl2tpd"
	}
	cp := "/etc/ppp/chap-secrets"
	if len(chapPath) > 0 && chapPath[0] != "" {
		cp = chapPath[0]
	}
	return &ConfManager{path: path, optionsPath: optionsPath, chapPath: cp}
}

// Sync 重写完整可用的 xl2tpd.conf（避免示例注释文件干扰）
func (c *ConfManager) Sync(active []model.TunnelMapping) error {
	c.mu.Lock()
	defer c.mu.Unlock()

	content, err := renderFullConf(active, c.optionsPath, c.chapPath)
	if err != nil {
		return err
	}
	previous, readErr := os.ReadFile(c.path)
	if readErr != nil && !os.IsNotExist(readErr) {
		return readErr
	}
	c.changed = semanticConf(string(previous)) != semanticConf(content)
	if c.changed && c.beforeChange != nil {
		if err := c.beforeChange(); err != nil {
			return err
		}
	}
	if err := c.ensureOptions(); err != nil {
		return err
	}

	if err := os.MkdirAll(filepath.Dir(c.path), 0o755); err != nil {
		return err
	}
	tmp := c.path + ".s2l.tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, c.path)
}

func semanticConf(content string) string {
	var lines []string
	for _, line := range strings.Split(content, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, ";") || strings.HasPrefix(line, "#") {
			continue
		}
		lines = append(lines, line)
	}
	return strings.Join(lines, "\n")
}
func (c *ConfManager) Changed() bool { c.mu.Lock(); defer c.mu.Unlock(); return c.changed }

func (c *ConfManager) ensureOptions() error {
	if err := os.MkdirAll(filepath.Dir(c.optionsPath), 0o755); err != nil {
		return err
	}
	// 每次 Sync 覆盖。注意：部分 pppd/pppol2tp 组合不支持 lock
	content := `# generated by s2l - L2TP LNS
refuse-eap
refuse-pap
require-chap
require-mschap-v2
noccp
auth
nodefaultroute
mtu 1400
mru 1400
lcp-echo-interval 30
lcp-echo-failure 4
connect-delay 5000
`
	for _, address := range model.ClientDNSAddresses() {
		content += "ms-dns " + address + "\n"
	}
	if err := c.ensureEventScripts(); err != nil {
		return err
	}
	content += fmt.Sprintf("ip-up-script %s\nip-down-script %s\n", c.optionsPath+".s2l-up", c.optionsPath+".s2l-down")
	previous, err := os.ReadFile(c.optionsPath)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if string(previous) == content {
		return nil
	}
	tmp := c.optionsPath + ".s2l.tmp"
	if err := os.WriteFile(tmp, []byte(content), 0644); err != nil {
		return err
	}
	defer os.Remove(tmp)
	return os.Rename(tmp, c.optionsPath)
}

func renderFullConf(active []model.TunnelMapping, optionsPath string, chapPath ...string) (string, error) {
	authPath := "/etc/ppp/chap-secrets"
	if len(chapPath) > 0 && chapPath[0] != "" {
		authPath = chapPath[0]
	}
	var b strings.Builder
	b.WriteString(confBegin + "\n")
	b.WriteString("; generated by s2l - xl2tpd comments must use ';'\n")
	b.WriteString("[global]\n")
	b.WriteString("port = 1701\n")
	b.WriteString(fmt.Sprintf("auth file = %s\n", authPath))
	b.WriteString("access control = no\n")
	b.WriteString("\n")

	b.WriteString("[lns default]\n")
	b.WriteString("ip range = 10.0.0.2-10.0.255.254\n")
	b.WriteString("local ip = 10.255.254.1\n")
	b.WriteString("require chap = yes\n")
	b.WriteString("refuse pap = yes\n")
	b.WriteString("require authentication = yes\n")
	b.WriteString("name = s2l\n")
	b.WriteString(fmt.Sprintf("pppoptfile = %s\n", optionsPath))
	b.WriteString("length bit = yes\n")
	b.WriteString("\n")

	if len(active) == 0 {
		b.WriteString("; (no active L2TP mappings)\n")
	} else {
		for _, m := range active {
			localIP, err := LocalIPFromSubnet(m.Subnet)
			if err != nil {
				return "", fmt.Errorf("mapping %s: %w", m.ID, err)
			}
			clientIP, err := ClientIPFromSubnet(m.Subnet)
			if err != nil {
				return "", fmt.Errorf("mapping %s: %w", m.ID, err)
			}
			b.WriteString(fmt.Sprintf("; map %s tun=%s table=%d user=%s peer=%s gw=%s\n",
				m.ID, m.TunName, m.TableID, m.L2TPUser, clientIP, localIP))
		}
	}
	b.WriteString(confEnd + "\n")
	return b.String(), nil
}

func (c *ConfManager) ensureEventScripts() error {
	for _, kind := range []string{"up", "down"} {
		// pppd supplies interface, tty, speed, local IP, peer IP and ipparam.
		script := `#!/bin/sh
python3 -c 'import socket,json,sys,os,datetime
try:
 s=socket.socket(socket.AF_UNIX,socket.SOCK_DGRAM);s.settimeout(0.3)
 s.sendto(json.dumps({"kind":"KIND","interface":sys.argv[1],"peer":sys.argv[5],"pid":int(os.environ.get("PPPD_PID","0")),"at":datetime.datetime.now(datetime.timezone.utc).isoformat()}).encode(),"/run/s2l/ppp-events.sock")
except Exception: pass
' "$@"
if [ -x /etc/ppp/ip-KIND ]; then exec /etc/ppp/ip-KIND "$@"; fi
exit 0
`
		script = strings.ReplaceAll(script, "KIND", kind)
		path := c.optionsPath + ".s2l-" + kind
		if err := writeEventScript(path, []byte(script)); err != nil {
			return err
		}
	}
	return nil
}

// PPP can launch a hook while another mapping is being started. Replace the
// complete script atomically, and leave an identical executable untouched.
func writeEventScript(path string, data []byte) error {
	if old, e := os.ReadFile(path); e == nil && string(old) == string(data) {
		if info, e := os.Stat(path); e == nil && info.Mode().Perm() == 0700 {
			return nil
		}
	}
	f, e := os.CreateTemp(filepath.Dir(path), ".ppp-hook-*")
	if e != nil {
		return e
	}
	defer os.Remove(f.Name())
	if e = f.Chmod(0700); e == nil {
		_, e = f.Write(data)
	}
	if e == nil {
		e = f.Sync()
	}
	closeErr := f.Close()
	if e == nil {
		e = closeErr
	}
	if e != nil {
		return e
	}
	return os.Rename(f.Name(), path)
}
